/** Stores the help examples' answers in src/help/results.ts. Run after changing any help example. */
import { writeFileSync } from 'node:fs';
import { allAnswers } from '../help/compute.js';

const answers = allAnswers();
const keys = Object.keys(answers).sort();
const body = keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(answers[k])},`).join('\n');
writeFileSync(new URL('../help/results.ts', import.meta.url), `// Generated by \`npm run help:results\` from the help examples. Don't edit.\nexport const RESULTS: Record<string, string[]> = {\n${body}\n};\n`);
console.log(`${keys.length} examples`);
